#!/usr/bin/env python3
"""Read-only reference snapshot. Labels are never included in reconstruction seeds."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import urllib.request
from datetime import UTC, datetime
from pathlib import Path

from genesis_curation.scatac import workbook

SHEET = "1Rq3J5U8-IDsR1n9kVbRCGC6om7aYdSkL8BsBe4woH0Q"
URL = f"https://docs.google.com/spreadsheets/d/{SHEET}/export?format=xlsx"
TABS = ("TSS Fable Curated", "Bulk ATAC Fable Curated", "scATAC Fable Curated")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=False)
    with urllib.request.urlopen(URL, timeout=60) as response:
        raw = response.read(32 * 1024**2 + 1)
    if len(raw) > 32 * 1024**2:
        raise ValueError("Reference workbook exceeds snapshot budget")
    path = args.output / "reference.xlsx"
    path.write_bytes(raw)
    sheets = workbook.read(path)
    manifest = {
        "source": URL,
        "retrieved_at": datetime.now(UTC).isoformat(),
        "sha256": hashlib.sha256(raw).hexdigest(),
        "role": "external-reference-not-gold",
        "origin": "People and other LLM workflows; not generated by this pipeline",
        "tabs": {},
    }
    seeds = set()
    for name in TABS:
        rows = sheets[name]
        headers = {
            re.sub(r"\d+$", "", key): value["value"] for key, value in rows[0]["cells"].items()
        }
        parsed = []
        for row in rows[1:]:
            values = {
                headers.get(re.sub(r"\d+$", "", key), ""): cell["value"]
                for key, cell in row["cells"].items()
            }
            values.pop("", None)
            parsed.append(values)
            for field in ("sra_study", "study_accession", "geo_series", "bioproject"):
                for accession in re.findall(
                    r"\b(?:GSE|[SED]RP|PRJ[EDN][AB])\d+\b", values.get(field, "")
                ):
                    seeds.add(accession)
        manifest["tabs"][name] = {"rows": len(parsed), "columns": list(headers.values())}
        (args.output / (name.replace(" ", "-") + ".json")).write_text(
            json.dumps(parsed, indent=2) + "\n"
        )
    (args.output / "reconstruction-accessions.txt").write_text("\n".join(sorted(seeds)) + "\n")
    (args.output / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps(manifest))


if __name__ == "__main__":
    main()
